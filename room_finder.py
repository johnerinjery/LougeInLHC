#!/usr/bin/env python3
"""
Room Finder
===========
Reads a timetable JSON that sits in the same folder as this program and writes
index.html next to it: a single self-contained page that shows which LHC and
NLH rooms are free at a chosen day and time. The timetable is embedded in the
page, so index.html opens straight from disk and can be copied or hosted
anywhere. No server is needed.

Usage
-----
    python room_finder.py                 write index.html and open it
    python room_finder.py --file x.json   use a specific JSON
    python room_finder.py --out page.html write to a different file name
    python room_finder.py --no-open       write the file but do not open it
    python room_finder.py --force         overwrite an index.html this program did not make
    python room_finder.py --serve         live mode: serve the page locally and re-read
                                          the JSON on every refresh (see --port)

index.html is a snapshot. After the timetable changes, run this program again.
An existing index.html that this program did not create is never overwritten
unless you pass --force.

Needs only Python 3.8 or newer. Nothing to install.
"""
import argparse
import json
import sys
import threading
import webbrowser
from datetime import datetime
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import urlparse

APP_NAME = "Room Finder"
DEFAULT_PORT = 8765
MARK = "<!-- Generated by Room Finder. Safe to overwrite. -->"


def app_dir() -> Path:
    """Folder holding this program (also works when frozen with PyInstaller)."""
    if getattr(sys, "frozen", False):
        return Path(sys.executable).resolve().parent
    return Path(__file__).resolve().parent


def looks_like_timetable(obj) -> bool:
    return isinstance(obj, dict) and isinstance(obj.get("year_groups"), dict)


def load_timetable(folder: Path, explicit: str = None):
    """Return (path, data). Raises LookupError with a readable message."""
    if explicit:
        path = Path(explicit)
        if not path.is_absolute():
            path = (folder / path) if (folder / path).exists() else (Path.cwd() / path)
        if not path.is_file():
            raise LookupError(f"The file {explicit!r} was not found.")
        candidates = [path]
    else:
        candidates = sorted(folder.glob("*.json"), key=lambda p: p.stat().st_mtime, reverse=True)
        if not candidates:
            raise LookupError(
                f"No .json file was found in {folder}. "
                "Put the timetable JSON in the same folder as room_finder.py."
            )

    problems = []
    for path in candidates:
        try:
            with open(path, "r", encoding="utf-8-sig") as fh:
                data = json.load(fh)
        except (OSError, ValueError) as err:
            problems.append(f"{path.name}: could not be read as JSON ({err})")
            continue
        if looks_like_timetable(data):
            return path, data
        problems.append(f"{path.name}: has no \"year_groups\" section")
    raise LookupError(
        "None of the JSON files here looks like a timetable. " + "; ".join(problems) + "."
    )


# --------------------------------------------------------------------------
# Static output: index.html with the timetable embedded
# --------------------------------------------------------------------------

def js_literal(value) -> str:
    """JSON text that is safe inside an HTML <script> block."""
    text = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    return (text.replace("<", "\\u003c")        # no </script> or <!-- inside the data
                .replace(" ", "\\u2028")
                .replace(" ", "\\u2029"))


def render_page(data, filename: str) -> str:
    built = datetime.now().strftime("%d %b %Y, %H:%M")
    block = ("<script>window.ROOMFINDER_DATA=" + js_literal(data) +
             ";window.ROOMFINDER_FILE=" + js_literal(filename) +
             ";window.ROOMFINDER_BUILT=" + js_literal(built) + ";</script>")
    page = PAGE.replace("<!--__DATA__-->", block, 1)
    return page.replace("<!doctype html>\n", "<!doctype html>\n" + MARK + "\n", 1)


def may_overwrite(out: Path, force: bool) -> bool:
    if not out.exists() or force:
        return True
    try:
        head = out.read_text(encoding="utf-8", errors="ignore")[:600]
    except OSError:
        return False
    return MARK in head


def write_page(folder: Path, args) -> int:
    try:
        path, data = load_timetable(folder, args.file)
    except LookupError as err:
        print(f"{APP_NAME}: {err}")
        return 1

    out = Path(args.out) if args.out else folder / "index.html"
    if not out.is_absolute():
        out = folder / out
    if not may_overwrite(out, args.force):
        print(f"{APP_NAME}: {out} already exists and was not made by this program, so it was left alone.")
        print("Use --out other.html to write somewhere else, or --force to overwrite it.")
        return 1

    html = render_page(data, path.name)
    tmp = out.with_name(out.name + ".tmp")
    try:
        tmp.write_text(html, encoding="utf-8", newline="\n")
        tmp.replace(out)
    except OSError as err:
        print(f"{APP_NAME}: could not write {out} ({err})")
        return 1

    print(f"{APP_NAME}: read {path.name}")
    print(f"{APP_NAME}: wrote {out}")
    if not args.no_open:
        webbrowser.open(out.resolve().as_uri())
    return 0


# --------------------------------------------------------------------------
# Optional live mode: --serve
# --------------------------------------------------------------------------

def make_handler(folder: Path, explicit: str):
    class Handler(BaseHTTPRequestHandler):
        server_version = "RoomFinder/1.0"

        def log_message(self, fmt, *args):  # keep the console quiet
            pass

        def _send(self, status, body: bytes, ctype: str):
            self.send_response(status)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.send_header("X-Content-Type-Options", "nosniff")
            self.end_headers()
            if self.command != "HEAD":
                self.wfile.write(body)

        def _json(self, status, obj):
            self._send(status, json.dumps(obj).encode("utf-8"), "application/json; charset=utf-8")

        def do_HEAD(self):
            self.do_GET()

        def do_GET(self):
            route = urlparse(self.path).path
            if route in ("/", "/index.html"):
                self._send(200, PAGE.encode("utf-8"), "text/html; charset=utf-8")
            elif route == "/api/data":
                try:
                    path, data = load_timetable(folder, explicit)
                except LookupError as err:
                    self._json(404, {"error": str(err)})
                    return
                self._json(200, {"file": path.name, "data": data})
            elif route == "/favicon.ico":
                self._send(204, b"", "image/x-icon")
            else:
                self._json(404, {"error": "Not found"})

    return Handler


def bind(port: int, handler):
    """Try the requested port, then the next few, then any free port."""
    for p in list(range(port, port + 20)) + [0]:
        try:
            return ThreadingHTTPServer(("127.0.0.1", p), handler)
        except OSError:
            continue
    raise SystemExit("Could not open a local port. Close other programs and try again.")


def serve(folder: Path, args) -> int:
    try:
        path, _ = load_timetable(folder, args.file)
        print(f"{APP_NAME}: using {path.name}")
    except LookupError as err:
        # Still start, so the page can show the same message and recover on refresh.
        print(f"{APP_NAME}: {err}")

    server = bind(args.port, make_handler(folder, args.file))
    url = f"http://127.0.0.1:{server.server_address[1]}/"
    print(f"{APP_NAME} is running at {url}")
    print("Edit or replace the JSON, then refresh the page. Press Ctrl+C here to quit.")
    if not args.no_open:
        threading.Timer(0.4, lambda: webbrowser.open(url)).start()
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nStopped.")
    finally:
        server.server_close()
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description="Write index.html showing which LHC and NLH rooms are free, from a timetable JSON."
    )
    ap.add_argument("--file", help="timetable JSON to use (default: newest valid .json beside this program)")
    ap.add_argument("--out", help="output file name (default: index.html beside this program)")
    ap.add_argument("--no-open", "--no-browser", dest="no_open", action="store_true",
                    help="do not open the result in the browser")
    ap.add_argument("--force", action="store_true", help="overwrite the output even if this program did not make it")
    ap.add_argument("--serve", action="store_true",
                    help="serve the page locally and re-read the JSON on every refresh, instead of writing a file")
    ap.add_argument("--port", type=int, default=DEFAULT_PORT, help=f"port for --serve (default {DEFAULT_PORT})")
    args = ap.parse_args(argv)

    folder = app_dir()
    return serve(folder, args) if args.serve else write_page(folder, args)


